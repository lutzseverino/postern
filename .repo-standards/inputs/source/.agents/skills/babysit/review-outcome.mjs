// The five-line record the Reviews section described before the verdict line
// and findings table; read for one release (ADR 0044).
const fiveLinePlaceholders = [
  "<the Standards review's actual outcome>",
  "<the Spec review's actual outcome>",
  "<Nothing, or what this round fixed>",
  "<None, or one list item per finding below>",
  "<the finding>",
];
const fields = ["Head", "Standards", "Spec", "Fixed", "Findings"];
const field = new RegExp(`^(${fields.join("|")}):[\\t ]*(.*?)[\\t ]*$`);
const item = /^[-*][\t ]+/;
// A finding starts with its file and line, optionally in a code span.
const located = /^[-*][\t ]+(`?)[^\s`<>]+:\d+(?:-\d+)?\1[\t ]+\S/;

const completed = (value) =>
  Boolean(value?.trim()) &&
  !/^(?:TODO|TBD|placeholder|_?No response_?|<[^>]*>|\[[^\]]*\]|\{[^}]*\})[.!]?$/i.test(
    value,
  ) &&
  !fiveLinePlaceholders.some((placeholder) => value.includes(placeholder));

const blank = (text) => text.replace(/[^\r\n]/g, " ");

const exampleElements = new Set([
  "blockquote",
  "code",
  "pre",
  "kbd",
  "script",
  "style",
  "textarea",
  "title",
  "xmp",
  "iframe",
  "noembed",
  "noframes",
]);
const normalElements = new Set(["blockquote", "code", "pre", "kbd"]);

function htmlContext(raw, context) {
  let at = 0;
  while (at < raw.length) {
    const element = context.elements.at(-1);
    // Raw-text elements do not nest. Their first matching end tag closes
    // them even when it occurs inside otherwise tag-shaped or comment text.
    if (element && !normalElements.has(element)) {
      const close = new RegExp(`</${element}\\s*>`, "i").exec(raw.slice(at));
      if (!close) return;
      context.elements.pop();
      at += close.index + close[0].length;
      continue;
    }
    const start = raw.indexOf("<", at);
    if (start < 0) return;
    // A block HTML token can contain several tags. Reuse Marked's HTML-token
    // rule so comments and quoted attributes cannot masquerade as end tags.
    const html = marked.Lexer.rules.inline.normal.tag.exec(raw.slice(start));
    at = start + (html?.[0].length ?? 1);
    if (!html) continue;
    const tag = /^<(\/?)([a-z][\w:-]*)(?=[\s/>])/i.exec(html[0]);
    if (!tag) continue;
    const name = tag[2].toLowerCase();
    if (tag[1] && name === "blockquote") {
      const quote = context.elements.lastIndexOf(name);
      // A quote closes its normal descendants. Active code formatting is
      // reconstructed outside it; a raw-text child consumes the end tag above.
      if (quote >= 0)
        context.elements.splice(
          quote,
          context.elements.length - quote,
          ...context.elements
            .slice(quote + 1)
            .filter((name) => name === "code"),
        );
    } else if (tag[1] && element === name) context.elements.pop();
    else if (!tag[1] && exampleElements.has(name)) context.elements.push(name);
  }
}

// Keep character offsets while excluding inline metadata. Its non-rendered line
// breaks and code-span line breaks become spaces, as their displayed text does.
// A child that cannot be located hides its parent instead of exposing evidence.
function shown(token, context) {
  if (token.type === "html") {
    htmlContext(token.raw, context);
    return " ".repeat(token.raw.length);
  }
  if (token.type === "image") return " ".repeat(token.raw.length);
  if (token.type === "codespan")
    return context.elements.length
      ? " ".repeat(token.raw.length)
      : token.raw.replace(/[\r\n]/g, " ");
  if (token.type === "link" && !token.autolink) {
    // Marked removes escaped brackets from a link's label. Locate that label
    // only at its source prefix; titles and reference/destination syntax never
    // participate in the recursive read. Keep the brackets themselves so
    // removing markup cannot manufacture a field at either end of the label.
    let end = 1;
    for (let index = 0; index < token.text.length; index++, end++) {
      if (token.raw[end] !== token.text[index]) {
        if (token.raw[end] !== "\\" || token.raw[end + 1] !== token.text[index])
          return blank(token.raw);
        end++;
      }
    }
    if (token.raw[0] !== "[" || token.raw[end] !== "]") return blank(token.raw);
    const label = shown(
      {
        type: "text",
        raw: token.text,
        tokens: token.tokens,
      },
      context,
    );
    if (!label.trim()) return blank(token.raw);
    const padding = " ".repeat(end - 1 - token.text.length);
    // Retain link delimiters so a visible label is not mistaken for a plain
    // bracketed placeholder after its metadata is hidden.
    const metadata = token.raw.slice(end + 1).replace(/[^\r\n()[\]]/g, " ");
    return `[${label}]${padding}${metadata}`;
  }
  let text = context.elements.length ? " ".repeat(token.raw.length) : token.raw;
  let at = 0;
  let visibleChild = false;
  for (const child of token.tokens ?? []) {
    const start = token.raw.indexOf(child.raw, at);
    if (start < 0) return blank(token.raw);
    const content = shown(child, context);
    visibleChild ||= Boolean(content.trim());
    text =
      text.slice(0, start) + content + text.slice(start + child.raw.length);
    at = start + child.raw.length;
  }
  // Delimiters around hidden children are not an outcome of their own.
  if (["strong", "em", "del"].includes(token.type) && !visibleChild)
    return blank(token.raw);
  return text;
}

// The lines a reader sees outside examples, built from the visible tokens
// rather than by masking source positions, which tokenization does not always
// preserve. Any other token, such as code, a quote, raw HTML or a link
// definition, becomes one blank line, so its content can neither supply
// evidence nor join the lines around it. Text keeps its lines inside list
// items too, so a field continuing an item still counts. An item's first line
// keeps its marker unless an example opens it, indented when nested, so only
// top-level items are findings. A top-level table also records its visible
// cells in the context, read in the same order as the lines around it.
function visibleLines(tokens, nested = false, context = { elements: [] }) {
  return tokens.flatMap((token) => {
    if (token.type === "table") {
      const cells = (row) =>
        row.map((cell) =>
          shown({ type: "text", raw: cell.text, tokens: cell.tokens }, context)
            .replace(/\s+/g, " ")
            .trim(),
        );
      const table = { header: cells(token.header), rows: token.rows.map(cells) };
      if (!nested) context.tables?.push(table);
      return [""];
    }
    if (token.type === "blockquote") {
      htmlContext("<blockquote>", context);
      visibleLines(token.tokens, true, context);
      htmlContext("</blockquote>", context);
      return [""];
    }
    if (["paragraph", "text", "heading"].includes(token.type))
      return shown(token, context).replace(/\n+$/, "").split("\n");
    // A closing tag can be a separate block token after an inline opening.
    // The block's own content remains excluded.
    if (token.type === "html") htmlContext(token.raw, context);
    if (token.type !== "list") return [""];
    return token.items.flatMap((entry) => {
      // Marked separates a task checkbox from its text. Keep them on the
      // same line, even when comments hide all remaining text, so task
      // findings and field-shaped tasks retain their marker.
      const checkbox =
        entry.tokens[0]?.type === "checkbox" ? entry.tokens[0].raw : "";
      const content = checkbox ? entry.tokens.slice(1) : entry.tokens;
      const [first, ...rest] = visibleLines(content, true, context);
      const marker = /^[\t ]*\S+[\t ]*/.exec(entry.raw)?.[0] ?? "";
      const opening = (nested ? "  " : "") + marker + checkbox + first;
      return [checkbox || first?.trim() ? opening : "", ...rest];
    });
  });
}

// A five-line record's fields, or null when it is not one: the head it names,
// whether it is complete, and whether it holds (complete, with no open
// finding).
function readFiveLines(lines) {
  const entries = lines.flatMap((line, index) => {
    const match = field.exec(line);
    return match ? [{ key: match[1], value: match[2], index }] : [];
  });
  if (
    entries.length !== fields.length ||
    new Set(entries.map(({ key }) => key)).size !== fields.length
  )
    return null;
  const byField = Object.fromEntries(
    entries.map((entry) => [entry.key, entry]),
  );
  const next = entries.find(({ index }) => index > byField.Findings.index);
  const findings = lines
    .slice(byField.Findings.index + 1, next?.index)
    .filter((line) => item.test(line));
  const none = /^None\.?$/i.test(byField.Findings.value);
  const findingsComplete = byField.Findings.value
    ? none && findings.length === 0
    : findings.length > 0 && findings.every((line) => located.test(line));
  const complete =
    ["Standards", "Spec", "Fixed"].every((key) =>
      completed(byField[key].value),
    ) && findingsComplete;
  return { head: byField.Head.value, complete, holds: complete && none };
}

const plain = (marker) => marker.replace(/\uFE0F/g, "");
// A round holds, hands back, fails or waits on a grill.
const leadMarkers = new Set(["✅", "🔁", "❌", "👤"]);
const pass = "✅";
const footer = /^Generated by AI · round ([1-9]\d*) · head (\S+)$/;
const lead = /^(\S+)[\t ]+\*\*(?=\S)(.*?\S)\*\*/;
// A holding or handed-back round names its round, as the footer does, and
// says which it is.
const roundLead = /^Round ([1-9]\d*) (holds|hands back)\b/;
const roundOutcomes = { [pass]: "holds", "🔁": "hands back" };
const verdict =
  /^\*\*Standards\*\*[\t ]+(\S+)[\t ]+(.+?)[\t ]+·[\t ]+\*\*Spec\*\*[\t ]+(\S+)[\t ]+(.+?)$/;
// An axis outcome: Pass or Fail, optionally with a comma and a note.
const outcome = /^(Pass|Fail)(?:,[\t ]*(.*))?$/;
const outcomes = { [pass]: "Pass", "❌": "Fail" };
const findingsHeader = ["Axis", "Where", "Finding", "State"];
const where = /^(`?)[^\s`<>]+:\d+(?:-\d+)?\1$/;
const state = /^(\S+?)\uFE0F?[\t ]+(Open|Fixed in|Filed)(?:[\t ]+(.*))?$/;
const states = { Open: "🔁", "Fixed in": "✅", Filed: "↗" };

// A finding row's state, or null when the row is incomplete: open, or settled
// by the commit that fixed it or the issue that filed it.
function readRow([axis, location, finding, cell]) {
  const match = state.exec(cell ?? "");
  if (
    !["Standards", "Spec"].includes(axis) ||
    !where.test(location ?? "") ||
    !completed(finding) ||
    !match ||
    plain(match[1]) !== states[match[2]] ||
    (match[2] === "Open" ? match[3] : !completed(match[3]))
  )
    return null;
  return { axis, state: match[2] };
}

// An axis passes, or fails with an open finding of its own; a note after a
// comma is filled.
function readAxis(name, marker, text, rows) {
  const match = outcome.exec(text);
  return (
    Boolean(match) &&
    outcomes[plain(marker)] === match[1] &&
    (match[2] === undefined || completed(match[2])) &&
    (match[1] === "Pass" ||
      rows.some((row) => row?.axis === name && row.state === "Open"))
  );
}

// A review led by its lead line, with a verdict line, findings table and
// footer, or null when it has no footer: the head and completeness the footer
// and its parts give. Its lead line passes exactly when no finding is open,
// which is when the round holds.
function readRecord(lines, tables) {
  const visible = lines.map((line) => line.trim()).filter(Boolean);
  const footers = visible.map((line) => footer.exec(line)).filter(Boolean);
  if (footers.length === 0) return null;
  const verdicts = visible.map((line) => verdict.exec(line)).filter(Boolean);
  const leading = lead.exec(visible[0]);
  const findings = tables.filter(({ header }) =>
    header.every((cell, index) => cell === findingsHeader[index]) &&
    header.length === findingsHeader.length,
  );
  const rows = findings[0]?.rows.map(readRow) ?? [];
  const open = rows.filter((row) => row?.state === "Open").length;
  const round = roundLead.exec(leading?.[2] ?? "");
  const complete =
    footers.length === 1 &&
    verdicts.length === 1 &&
    readAxis("Standards", verdicts[0][1], verdicts[0][2], rows) &&
    readAxis("Spec", verdicts[0][3], verdicts[0][4], rows) &&
    Boolean(leading) &&
    leadMarkers.has(plain(leading[1])) &&
    (plain(leading[1]) === pass) === (open === 0) &&
    (!(plain(leading[1]) in roundOutcomes) ||
      (round?.[1] === footers[0][1] &&
        round[2] === roundOutcomes[plain(leading[1])])) &&
    findings.length <= 1 &&
    (findings.length === 0 || rows.length > 0) &&
    rows.every(Boolean);
  return { head: footers[0][2], complete, holds: complete && open === 0 };
}

// A review in either shape, or null when it is neither. A visible footer line
// makes it the lead-line record; otherwise it is read as the five-line record.
function readReview(body) {
  if (typeof body !== "string") return null;
  const context = { elements: [], tables: [] };
  const lines = visibleLines(marked.lexer(body), false, context);
  return lines.some((line) => line.trim().startsWith("Generated by AI · "))
    ? readRecord(lines, context.tables)
    : readFiveLines(lines);
}

// The full head SHA a review names, if any.
export function reviewedHead(body) {
  const head = readReview(body)?.head;
  return /^[0-9a-f]{40}$/.test(head ?? "") ? head : null;
}

export function completeReview(body, head) {
  const review = readReview(body);
  return review !== null && review.head === head && review.complete;
}

// A review holds when it is complete and leaves no open finding.
export function holdingReview(body, head) {
  const review = readReview(body);
  return review !== null && review.head === head && review.holds;
}
